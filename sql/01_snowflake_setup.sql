
-- Retail Sales Data Pipeline
-- Phase 3: Snowflake Infrastructure Setup

-- Database and schemas
CREATE DATABASE IF NOT EXISTS RETAIL_SALES_DB;

CREATE SCHEMA IF NOT EXISTS RETAIL_SALES_DB.RAW;
CREATE SCHEMA IF NOT EXISTS RETAIL_SALES_DB.STAGING;
CREATE SCHEMA IF NOT EXISTS RETAIL_SALES_DB.ANALYTICS;

-- Compute warehouse
CREATE WAREHOUSE IF NOT EXISTS RETAIL_SALES_WH
WITH
    WAREHOUSE_SIZE = 'XSMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE
    MIN_CLUSTER_COUNT = 1
    MAX_CLUSTER_COUNT = 1;

-- Resource monitor
CREATE RESOURCE MONITOR IF NOT EXISTS RETAIL_SALES_MONITOR
WITH
    CREDIT_QUOTA = 5
    FREQUENCY = MONTHLY
    START_TIMESTAMP = IMMEDIATELY
    TRIGGERS
        ON 75 PERCENT DO NOTIFY
        ON 100 PERCENT DO SUSPEND_IMMEDIATE;

ALTER WAREHOUSE RETAIL_SALES_WH
SET RESOURCE_MONITOR = RETAIL_SALES_MONITOR;

-- Retail Sales Data Pipeline
-- Optional one-time Snowflake CI access setup.
-- Run as ACCOUNTADMIN after 01_snowflake_setup.sql, 03_raw_data_load.sql,
-- and the dbt analytics models have been created.
-- Never store an RSA private key or actual public key in this repository.
-- The GitHub Actions workflow uses RETAIL_PIPELINE_CI / RETAIL_PIPELINE_ROLE.

USE ROLE ACCOUNTADMIN;

CREATE ROLE IF NOT EXISTS RETAIL_PIPELINE_ROLE;
GRANT ROLE RETAIL_PIPELINE_ROLE TO ROLE SYSADMIN;

GRANT USAGE ON WAREHOUSE RETAIL_SALES_WH TO ROLE RETAIL_PIPELINE_ROLE;
GRANT USAGE ON DATABASE RETAIL_SALES_DB TO ROLE RETAIL_PIPELINE_ROLE;
GRANT USAGE ON SCHEMA RETAIL_SALES_DB.RAW TO ROLE RETAIL_PIPELINE_ROLE;
GRANT USAGE ON SCHEMA RETAIL_SALES_DB.STAGING TO ROLE RETAIL_PIPELINE_ROLE;
GRANT USAGE ON SCHEMA RETAIL_SALES_DB.ANALYTICS TO ROLE RETAIL_PIPELINE_ROLE;

GRANT CREATE TABLE, CREATE STAGE
    ON SCHEMA RETAIL_SALES_DB.RAW TO ROLE RETAIL_PIPELINE_ROLE;
GRANT SELECT, INSERT, DELETE
    ON TABLE RETAIL_SALES_DB.RAW.LIQUOR_SALES TO ROLE RETAIL_PIPELINE_ROLE;
GRANT SELECT, INSERT
    ON TABLE RETAIL_SALES_DB.RAW.INGESTION_HISTORY TO ROLE RETAIL_PIPELINE_ROLE;
GRANT CREATE TABLE, CREATE VIEW
    ON SCHEMA RETAIL_SALES_DB.STAGING TO ROLE RETAIL_PIPELINE_ROLE;
GRANT CREATE TABLE, CREATE VIEW
    ON SCHEMA RETAIL_SALES_DB.ANALYTICS TO ROLE RETAIL_PIPELINE_ROLE;

-- CAUTION: Existing dbt model objects may be owned by another role.
-- The following grants were used during the original CI setup. Review
-- ownership/permissions before executing them in any new environment.
-- GRANT OWNERSHIP ON VIEW RETAIL_SALES_DB.STAGING.STG_LIQUOR_SALES
--     TO ROLE RETAIL_PIPELINE_ROLE COPY CURRENT GRANTS;
-- GRANT OWNERSHIP ON TABLE RETAIL_SALES_DB.ANALYTICS.DIM_STORE
--     TO ROLE RETAIL_PIPELINE_ROLE COPY CURRENT GRANTS;
-- GRANT OWNERSHIP ON TABLE RETAIL_SALES_DB.ANALYTICS.DIM_PRODUCT
--     TO ROLE RETAIL_PIPELINE_ROLE COPY CURRENT GRANTS;
-- GRANT OWNERSHIP ON TABLE RETAIL_SALES_DB.ANALYTICS.DIM_DATE
--     TO ROLE RETAIL_PIPELINE_ROLE COPY CURRENT GRANTS;
-- GRANT OWNERSHIP ON TABLE RETAIL_SALES_DB.ANALYTICS.FACT_SALES
--     TO ROLE RETAIL_PIPELINE_ROLE COPY CURRENT GRANTS;

CREATE USER IF NOT EXISTS RETAIL_PIPELINE_CI
    TYPE = SERVICE
    LOGIN_NAME = 'RETAIL_PIPELINE_CI'
    DEFAULT_ROLE = RETAIL_PIPELINE_ROLE
    DEFAULT_WAREHOUSE = RETAIL_SALES_WH;
GRANT ROLE RETAIL_PIPELINE_ROLE TO USER RETAIL_PIPELINE_CI;

-- Register the public portion of a dedicated CI RSA key via a private
-- administrative worksheet, not via committed SQL:
-- ALTER USER RETAIL_PIPELINE_CI SET RSA_PUBLIC_KEY = '<PUBLIC_KEY_BASE64>';
-- Supply the encrypted PRIVATE key and passphrase via GitHub Actions secrets.
-- Never put either secret in SQL or Git.

SHOW GRANTS TO ROLE RETAIL_PIPELINE_ROLE;
DESCRIBE USER RETAIL_PIPELINE_CI;
